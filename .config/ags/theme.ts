export interface Theme {
  name: string
  displayName: string
  colors: ThemeColors
  gtk: {
    theme: string
    iconTheme: string
    cursorTheme: string
    colorScheme: string
  }
  hyprland: {
    borderRadius: number
    gapsIn: number
    gapsOut: number
    borderSize: number
  }
  // Optional compositor "feel" (kit theme uses it). Themes without it get
  // DEFAULT_LOOK, which matches hypr/theme.lua + foot.ini's stock values.
  look?: ThemeLook
}

export interface ThemeLook {
  opacity?: number          // every window (fullscreen stays 1.0); foot uses terminalAlpha instead
  terminalAlpha?: number    // foot alpha (foot must be <1 itself for Hyprland ≥0.56 blur)
  dimInactive?: number      // 0 = off
  blur?: { size: number, passes: number, vibrancy: number }
  shadow?: { range: number, renderPower: number }
  panelAlpha?: number       // edge sidebar panel + handle background alpha (1 = opaque)
}

const DEFAULT_LOOK: Required<ThemeLook> = {
  opacity: 1,
  terminalAlpha: 0.75,
  dimInactive: 0.15,
  blur: { size: 6, passes: 3, vibrancy: 0.15 },
  shadow: { range: 4, renderPower: 3 },
  panelAlpha: 1,
}

// Hyprland Lua for a theme's layout + look. Applied live via `hyprctl eval`
// and also written to hypr/custom/theme.lua (loaded at startup) so the theme
// survives a login. The opacity rules are kept in _G so switching themes can
// switch them off again.
function themeHyprLua(t: Theme): string {
  const L = { ...DEFAULT_LOOK, ...(t.look ?? {}) }
  const h = t.hyprland
  const border = stripHash(t.colors.bg_dark)
  const lines = [
    "-- Generated by the AGS theme switcher (theme.ts) — overwritten on every theme change.",
    `-- Theme: ${t.name}`,
    "if _G.__theme_opacity then _G.__theme_opacity:set_enabled(false); _G.__theme_opacity = nil end",
    "if _G.__theme_opacity_keep then _G.__theme_opacity_keep:set_enabled(false); _G.__theme_opacity_keep = nil end",
    "if _G.__theme_opacity_fs then _G.__theme_opacity_fs:set_enabled(false); _G.__theme_opacity_fs = nil end",
    "hl.config({",
    `  general = { gaps_in = ${h.gapsIn}, gaps_out = ${h.gapsOut}, border_size = ${h.borderSize},`,
    `    col = { active_border = "rgb(${border})", inactive_border = "rgb(${border})" } },`,
    `  decoration = { rounding = ${h.borderRadius},`,
    `    dim_inactive = ${L.dimInactive > 0}, dim_strength = ${L.dimInactive || 0.15},`,
    `    blur = { enabled = true, size = ${L.blur.size}, passes = ${L.blur.passes}, vibrancy = ${L.blur.vibrancy} },`,
    `    shadow = { enabled = true, range = ${L.shadow.range}, render_power = ${L.shadow.renderPower} } },`,
    "})",
  ]
  if (L.opacity < 1) {
    lines.push(
      `_G.__theme_opacity = hl.window_rule({ name = "theme-opacity", match = { class = ".*" }, opacity = "${L.opacity} override" })`,
      `_G.__theme_opacity_fs = hl.window_rule({ name = "theme-opacity-fullscreen", match = { class = ".*", fullscreen_state_internal = 2 }, opacity = "1.0 override" })`,
    )
  }
  return lines.join("\n") + "\n"
}

// Helper to strip # from hex colors
function stripHash(color: string): string {
  return color.replace("#", "")
}

export function loadTheme(themeName: string): Theme | null {
  try {
    const content = readFile(`${THEME_DIR}/${themeName}.json`)
    if (!content) return null
    return JSON.parse(content) as Theme
  } catch (e) {
    print(`Error loading theme ${themeName}: ${e}`)
    return null
  }
}

